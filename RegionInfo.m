+ (NSDictionary *)regionForISO:(NSString *)iso {
    if (!iso.length) return nil;
    for (NSDictionary *r in [self allRegions]) {
        if ([r[@"code"] caseInsensitiveCompare:iso] == NSOrderedSame) {
            return r;
        }
    }
    return nil;
}

+ (NSDictionary *)currentRegion {
    NSString *iso = [[NSUserDefaults standardUserDefaults] stringForKey:@"selected_region_iso"];
    NSDictionary *r = [self regionForISO:iso];
    if (!r) {
        // fallback: KZ default (recommendations in Russia without VPN)
        r = [self regionForISO:@"KZ"];
    }
    if (!r) return nil;
    return @{
        @"area": [NSString stringWithFormat:@"%@ (%@)", r[@"name"], r[@"code"]],
        @"name": r[@"name"],
        @"code": r[@"code"],
        @"mcc": r[@"mcc"],
        @"mnc": r[@"mnc"]
    };
}

